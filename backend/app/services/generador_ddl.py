"""
DDL (PostgreSQL) del diagrama de clases — RF-BASE-07 y migración Flyway del
backend generado. Sale del mismo `ModeloRelacional` que las entidades JPA,
así lo que se exporta es exactamente lo que crea el backend.

Orden del script: primero todas las tablas (sin FKs), después las FKs con
`ALTER TABLE` (admite ciclos entre tablas), después los índices. Los
identificadores van entre comillas (el backend generado usa
`globally_quoted_identifiers`): un nombre de clase como "Order" o "User" no
choca con palabras reservadas. Compatible con H2 en `MODE=PostgreSQL`.
"""

from __future__ import annotations

from app.services.modelo_relacional import ModeloRelacional, identificador_sql


def _q(nombre: str) -> str:
    return '"' + nombre.replace('"', "") + '"'


def generar_ddl(nombre_proyecto: str, modelo: ModeloRelacional) -> str:
    tablas: list[str] = []
    restricciones: list[str] = []
    indices: list[str] = []

    for e in modelo.ordenadas():
        columnas: list[str] = []
        if e.id_padre:
            columnas.append(f"    {_q('id')} BIGINT PRIMARY KEY")
            padre = modelo.entidades[e.id_padre]
            restricciones.append(
                f"ALTER TABLE {_q(e.tabla)} ADD CONSTRAINT {_q(identificador_sql(f'fk_{e.tabla}_herencia'))} "
                f"FOREIGN KEY ({_q('id')}) REFERENCES {_q(padre.tabla)} ({_q('id')}) ON DELETE CASCADE;"
            )
        else:
            columnas.append(f"    {_q('id')} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        for a in e.atributos:
            columnas.append(f"    {_q(a.columna)} {a.tipo_sql}")
        claves = modelo.claves_de(e.clase.id)
        for k in claves:
            columnas.append(f"    {_q(k.columna)} BIGINT" + (" NOT NULL" if k.obligatoria else ""))
        de_asociacion = [k for k in claves if k.de_asociacion]
        if len(de_asociacion) == 2:
            cols = ", ".join(_q(k.columna) for k in de_asociacion)
            nombre = identificador_sql(f"uq_{e.tabla}_" + "_".join(k.columna for k in de_asociacion))
            columnas.append(f"    CONSTRAINT {_q(nombre)} UNIQUE ({cols})")
        for k in claves:
            if k.unica:
                nombre = identificador_sql(f"uq_{e.tabla}_{k.columna}")
                columnas.append(f"    CONSTRAINT {_q(nombre)} UNIQUE ({_q(k.columna)})")
        comentario = f"-- Clase {e.nombre_java}" + (" (abstracta)" if e.abstracta else "")
        if e.id_padre:
            comentario += f" — hereda de {modelo.entidades[e.id_padre].nombre_java} (tabla por subclase)"
        tablas.append(f"{comentario}\nCREATE TABLE {_q(e.tabla)} (\n" + ",\n".join(columnas) + "\n);")

        for k in claves:
            ref = modelo.entidades[k.id_referida]
            restricciones.append(
                f"ALTER TABLE {_q(e.tabla)} ADD CONSTRAINT {_q(identificador_sql(f'fk_{e.tabla}_{k.columna}'))} "
                f"FOREIGN KEY ({_q(k.columna)}) REFERENCES {_q(ref.tabla)} ({_q('id')}) ON DELETE {k.on_delete};"
            )
            if not k.unica:  # UNIQUE ya crea su índice
                indices.append(
                    f"CREATE INDEX {_q(identificador_sql(f'ix_{e.tabla}_{k.columna}'))} "
                    f"ON {_q(e.tabla)} ({_q(k.columna)});"
                )

    for m in modelo.muchos_a_muchos:
        if m.id_asociacion is not None:
            continue  # la tabla de la clase de asociación ya es la intermedia
        dueño, inverso = modelo.entidades[m.id_dueño], modelo.entidades[m.id_inverso]
        tablas.append(
            f"-- N:M {dueño.nombre_java} *--* {inverso.nombre_java}\n"
            f"CREATE TABLE {_q(m.tabla)} (\n"
            f"    {_q(m.columna_dueño)} BIGINT NOT NULL,\n"
            f"    {_q(m.columna_inverso)} BIGINT NOT NULL,\n"
            f"    PRIMARY KEY ({_q(m.columna_dueño)}, {_q(m.columna_inverso)})\n"
            ");"
        )
        for col, ref in ((m.columna_dueño, dueño), (m.columna_inverso, inverso)):
            restricciones.append(
                f"ALTER TABLE {_q(m.tabla)} ADD CONSTRAINT {_q(identificador_sql(f'fk_{m.tabla}_{col}'))} "
                f"FOREIGN KEY ({_q(col)}) REFERENCES {_q(ref.tabla)} ({_q('id')}) ON DELETE CASCADE;"
            )
        indices.append(
            f"CREATE INDEX {_q(identificador_sql(f'ix_{m.tabla}_{m.columna_inverso}'))} "
            f"ON {_q(m.tabla)} ({_q(m.columna_inverso)});"
        )

    avisos = "".join(f"-- AVISO: {a}\n" for a in modelo.avisos)
    partes = [
        f"-- Esquema generado por Diagramador UML para el proyecto \"{nombre_proyecto}\".\n"
        "-- Dialecto: PostgreSQL (compatible con H2 en MODE=PostgreSQL).\n" + avisos,
        "\n\n".join(tablas),
        "-- Claves foráneas\n" + "\n".join(restricciones) if restricciones else "",
        "-- Índices sobre claves foráneas\n" + "\n".join(indices) if indices else "",
    ]
    return "\n\n".join(p for p in partes if p) + "\n"
